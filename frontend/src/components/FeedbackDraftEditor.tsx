import React, { useEffect, useState } from 'react';
import {
  Bot,
  CheckCircle2,
  Edit2,
  FileCheck,
  MapPin,
  Save,
  Sparkles,
} from 'lucide-react';
import { DetailedFeedbackPayload, SubmissionGrade } from '../types';

interface FeedbackDraftEditorProps {
  grade: SubmissionGrade | null;
  onGenerate: () => Promise<void>;
  onSaveFeedback: (summary: string, detailed?: any, asConfirmed?: boolean) => Promise<void>;
  onSelectEvidence?: (evidenceId: string) => void;
}

export const FeedbackDraftEditor: React.FC<FeedbackDraftEditorProps> = ({
  grade,
  onGenerate,
  onSaveFeedback,
  onSelectEvidence,
}) => {
  const [isEditing, setIsEditing] = useState(false);
  const [editedSummary, setEditedSummary] = useState<string>(grade?.feedback_summary || '');
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  useEffect(() => {
    if (!isEditing) {
      setEditedSummary(grade?.feedback_summary || '');
    }
  }, [grade?.feedback_summary, grade?.submission_id, isEditing]);

  const detailed: DetailedFeedbackPayload | null = grade?.detailed_feedback || null;
  const isConfirmed = grade?.status === 'confirmed';

  const handleGenerateClick = async () => {
    setLoading(true);
    setError('');
    setNotice('');
    try {
      await onGenerate();
      setNotice('Feedback generated. Review it before confirming.');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not generate feedback. Please retry.');
    } finally {
      setLoading(false);
    }
  };

  const handleSaveClick = async (asConfirmed: boolean = false) => {
    setSaving(true);
    setError('');
    setNotice('');
    try {
      await onSaveFeedback(editedSummary, detailed, asConfirmed);
      setIsEditing(false);
      setNotice(asConfirmed ? 'Feedback confirmed.' : 'Feedback draft saved.');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Could not save feedback. Your text is still here.');
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="bg-[#FFFDF9] dark:bg-[#38322E] rounded-2xl border border-[#AEAC78]/35 dark:border-[#AEAC78]/25 shadow-sm p-5 text-xs flex flex-col h-full overflow-hidden text-[#4C4541] dark:text-[#FCF0DA]">
      <div className="flex flex-wrap gap-2 items-center justify-between pb-3 border-b border-[#AEAC78]/30 dark:border-[#AEAC78]/20 shrink-0">
        <div className="flex flex-wrap gap-2 items-center">
          <Bot className="w-4 h-4 text-[#AEAC78] dark:text-[#F2C46A]" />
          <h3 className="text-xs font-bold text-[#4C4541] dark:text-[#FCF0DA] uppercase tracking-wider">
            Evidence-Grounded Feedback
          </h3>
          {isConfirmed ? (
            <span className="bg-[#AEAC78]/25 text-[#2E4324] dark:text-[#FCF0DA] text-[10px] font-bold px-2 py-0.5 rounded border border-[#AEAC78]/50 inline-flex items-center gap-1">
              <CheckCircle2 className="w-3 h-3" />
              <span>Confirmed</span>
            </span>
          ) : (
            <span className="bg-[#F2C46A]/20 text-[#6B4307] dark:text-[#F2C46A] text-[10px] font-bold px-2 py-0.5 rounded border border-[#F2C46A]/40">
              Draft
            </span>
          )}
          {grade?.feedback_summary && (
            <span className="bg-[#FCF0DA]/50 dark:bg-[#2C2623] text-[#4C4541] dark:text-[#FCF0DA] text-[10px] font-semibold px-2 py-0.5 rounded border border-[#AEAC78]/40">
              {grade.feedback_source === 'gemini'
                ? 'Generated by Gemini'
                : grade.feedback_source === 'openai'
                ? 'Generated by OpenAI-compatible model'
                : grade.feedback_source === 'rules'
                ? 'Rule-based fallback (not AI)'
                : 'Source unknown (older record)'}
            </span>
          )}
        </div>

        <button
          onClick={handleGenerateClick}
          disabled={loading || saving || isEditing || !grade}
          className="px-2.5 py-1 bg-[#F2C46A] hover:bg-[#F2C46A]/90 text-[#4C4541] rounded-lg text-xs font-bold inline-flex items-center space-x-1.5 transition-colors border border-[#AEAC78]/60 shadow-xs cursor-pointer disabled:opacity-50"
          title="Generate feedback from evidence; uses rule-based fallback when AI is unavailable"
        >
          <Sparkles className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          <span>{loading ? 'Generating...' : 'Generate Feedback'}</span>
        </button>
      </div>

      <div className="flex-1 flex flex-col min-h-0 pt-3 space-y-3">
        {error && (
          <p
            role="alert"
            className="rounded-lg border border-rose-300 dark:border-rose-900 bg-rose-50 dark:bg-rose-950/50 p-3 text-sm text-rose-700 dark:text-rose-300 font-semibold shrink-0"
          >
            {error}
          </p>
        )}
        {notice && (
          <p role="status" className="text-sm font-semibold text-[#2E4324] dark:text-[#AEAC78] shrink-0">
            {notice}
          </p>
        )}
        {!grade && (
          <p className="text-sm text-[#4C4541]/70 dark:text-[#FCF0DA]/70 shrink-0">
            Calculate a grade first to enable feedback.
          </p>
        )}

        {/* Clickable Evidence Citation Anchors */}
        {detailed && detailed.citations && detailed.citations.length > 0 && (
          <div className="flex flex-wrap items-center gap-1.5 rounded-xl border border-[#AEAC78]/35 bg-[#FCF0DA]/40 dark:bg-[#2C2623]/60 px-3 py-2 shrink-0">
            <span className="font-mono text-[10px] font-bold uppercase tracking-wider text-[#4C4541]/80 dark:text-[#FCF0DA]/80 mr-1">
              Anchored Citations:
            </span>
            {detailed.citations.map((cid) => (
              <button
                key={cid}
                type="button"
                onClick={() => onSelectEvidence?.(cid)}
                className="inline-flex items-center gap-1 rounded-md border border-[#AEAC78]/50 bg-[#FFFDF9] dark:bg-[#38322E] px-2 py-0.5 font-mono text-[11px] font-bold text-[#4C4541] dark:text-[#FCF0DA] hover:bg-[#F2C46A] hover:text-[#4C4541] transition-colors cursor-pointer shadow-2xs"
                title={`Jump to evidence ${cid} in code and inspector`}
              >
                <MapPin className="w-3 h-3 text-[#2E6B56] dark:text-[#F2C46A]" />
                <span>[{cid}]</span>
              </button>
            ))}
          </div>
        )}

        {/* Structured Areas for Improvement (when available and not editing raw markdown) */}
        {!isEditing && detailed && detailed.areas_for_improvement && detailed.areas_for_improvement.length > 0 && (
          <div className="space-y-1.5 shrink-0">
            <span className="text-[11px] font-bold text-[#4C4541] dark:text-[#FCF0DA] uppercase tracking-wider block">
              Diagnostic Action Items ({detailed.areas_for_improvement.length})
            </span>
            <div className="space-y-1.5 max-h-36 overflow-y-auto pr-1">
              {detailed.areas_for_improvement.map((item, idx) => (
                <div
                  key={`${item.evidence_id}-${idx}`}
                  className="rounded-lg border border-[#AEAC78]/35 bg-[#FCF0DA]/25 dark:bg-[#2C2623]/50 p-2 text-[11px] flex items-start justify-between gap-2"
                >
                  <div className="min-w-0">
                    <p className="font-bold text-[#4C4541] dark:text-[#FCF0DA]">{item.issue}</p>
                    <p className="text-[#4C4541]/80 dark:text-[#FCF0DA]/80 mt-0.5">{item.suggestion}</p>
                  </div>
                  {item.evidence_id && (
                    <button
                      type="button"
                      onClick={() => onSelectEvidence?.(item.evidence_id)}
                      className="shrink-0 rounded bg-[#F2C46A]/35 hover:bg-[#F2C46A] px-1.5 py-0.5 font-mono text-[10px] font-bold text-[#4C4541] border border-[#AEAC78]/50 transition-colors cursor-pointer"
                    >
                      [{item.evidence_id}]
                    </button>
                  )}
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Full Markdown Summary Draft */}
        <div className="flex-1 flex flex-col min-h-0">
          <div className="flex items-center justify-between mb-2 shrink-0">
            <label className="font-bold text-[#4C4541] dark:text-[#FCF0DA]">
              Instructor Feedback Summary (Markdown)
            </label>
            {!isEditing && (
              <button
                disabled={!grade || loading || saving}
                onClick={() => {
                  setEditedSummary(grade?.feedback_summary || '');
                  setIsEditing(true);
                }}
                className="text-[#AEAC78] dark:text-[#F2C46A] hover:underline text-[11px] font-bold inline-flex items-center space-x-1 cursor-pointer disabled:opacity-40"
              >
                <Edit2 className="w-3 h-3" />
                <span>Edit Text</span>
              </button>
            )}
          </div>

          {isEditing ? (
            <textarea
              aria-label="Feedback summary"
              disabled={saving}
              rows={12}
              value={editedSummary}
              onChange={(e) => setEditedSummary(e.target.value)}
              className="flex-1 w-full font-mono text-xs p-3 border border-[#AEAC78]/60 rounded-xl text-[#4C4541] dark:text-[#FCF0DA] bg-[#FCF0DA]/30 dark:bg-[#2C2623] focus:outline-none focus:ring-2 focus:ring-[#F2C46A] resize-y"
              placeholder="Write or edit feedback for the student report..."
            />
          ) : (
            <div className="flex-1 overflow-y-auto p-3.5 bg-[#FCF0DA]/30 dark:bg-[#2C2623]/60 border border-[#AEAC78]/35 rounded-xl text-[#4C4541] dark:text-[#FCF0DA] text-xs whitespace-pre-wrap font-sans leading-relaxed">
              {grade?.feedback_summary || 'No feedback summary generated yet.'}
            </div>
          )}
        </div>
      </div>

      {/* Action Footer */}
      {isEditing && (
        <div className="mt-3 pt-2.5 border-t border-[#AEAC78]/30 dark:border-[#AEAC78]/20 flex items-center justify-end space-x-2 shrink-0">
          <button
            disabled={saving}
            onClick={() => setIsEditing(false)}
            className="px-3 py-1.5 border border-[#AEAC78]/60 hover:bg-[#FCF0DA] dark:hover:bg-[#2C2623] text-[#4C4541] dark:text-[#FCF0DA] rounded-lg font-medium cursor-pointer"
          >
            Cancel
          </button>
          <button
            onClick={() => handleSaveClick(false)}
            disabled={saving}
            className="px-3 py-1.5 border border-[#AEAC78]/60 hover:bg-[#F2C46A]/20 text-[#4C4541] dark:text-[#FCF0DA] rounded-lg font-medium inline-flex items-center space-x-1 cursor-pointer"
          >
            <Save className="w-3.5 h-3.5" />
            <span>Save Draft</span>
          </button>
          <button
            onClick={() => handleSaveClick(true)}
            disabled={saving}
            className="px-3.5 py-1.5 bg-[#F2C46A] hover:bg-[#F2C46A]/90 text-[#4C4541] font-bold rounded-lg border border-[#AEAC78]/60 shadow-xs inline-flex items-center space-x-1 cursor-pointer"
          >
            <FileCheck className="w-3.5 h-3.5" />
            <span>Confirm Feedback</span>
          </button>
        </div>
      )}
    </div>
  );
};
