import { test, expect } from '@playwright/test';
import { zipSync, strToU8 } from 'fflate';
import { readFile } from 'node:fs/promises';

test('instructor creates workspace, edits tests, imports, grades, reruns and exports', async ({ page }) => {
  const username = process.env.E2E_USERNAME;
  const password = process.env.E2E_PASSWORD;
  if (!username || !password) throw new Error('Set E2E_USERNAME and E2E_PASSWORD to a disposable local lecturer account.');
  const serverErrors: string[] = [];
  page.on('response', (response) => { if (response.status() >= 500) serverErrors.push(response.url()); });
  page.on('pageerror', (error) => serverErrors.push(error.message));
  page.on('dialog', (dialog) => void dialog.accept());
  await page.goto('/');
  await page.getByPlaceholder('lecturer_username').fill(username);
  await page.getByPlaceholder('Enter password').fill(password);
  await page.getByRole('button', { name: 'Sign In to Workstation' }).click();
  await page.getByRole('button', { name: 'Set Up Course & Class' }).click();
  await page.getByLabel('Course code', { exact: true }).fill(`E2E-${Date.now()}`);
  await page.getByLabel('Course name', { exact: true }).fill('Browser acceptance');
  await page.getByRole('button', { name: 'Create course', exact: true }).click();
  await page.getByLabel('Class code', { exact: true }).fill('E2E01');
  await page.getByLabel('Class name', { exact: true }).fill('Browser class');
  await page.getByRole('button', { name: 'Create class', exact: true }).click();
  await page.getByLabel('Assignment title', { exact: true }).fill('Addition');
  await page.getByRole('button', { name: 'Create assignment', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Addition revised');
  await page.getByLabel('Description', { exact: true }).fill('Add two integers');
  await page.getByLabel('Instructions', { exact: true }).fill('Implement add(a, b)');
  await page.getByLabel('Starter code', { exact: true }).fill('def add(a, b):\n    pass\n');
  await page.getByLabel('Status', { exact: true }).selectOption('published');
  await page.getByLabel('Deadline (local time)', { exact: true }).fill('2026-11-20T10:00');
  await page.getByRole('button', { name: 'Save assignment', exact: true }).click();
  await expect(page.getByText('Assignment saved.', { exact: true })).toBeVisible();
  await page.getByLabel('Deadline (local time)', { exact: true }).fill('');
  const clearResponse = page.waitForResponse(r => r.request().method() === 'PUT' && /\/assignments\/\d+$/.test(r.url()));
  await page.getByRole('button', { name: 'Save assignment', exact: true }).click();
  expect((await (await clearResponse).json()).deadline).toBeNull();

  for (const [name, visibility] of [['public_add', 'public'], ['hidden_add', 'hidden'], ['temporary', 'public']]) {
    await page.getByLabel('Test name', { exact: true }).fill(name);
    await page.getByLabel('Visibility', { exact: true }).selectOption(visibility);
    await page.getByRole('button', { name: 'Save test', exact: true }).click();
    await expect(page.getByTestId('test-row').filter({ hasText: name })).toBeVisible();
  }
  await page.getByTestId('test-row').filter({ hasText: 'temporary' }).getByRole('button', { name: 'Edit test' }).click();
  await page.getByLabel('Test name', { exact: true }).fill('temporary_edited');
  await page.getByRole('button', { name: 'Save test', exact: true }).click();
  await page.getByTestId('test-row').filter({ hasText: 'temporary_edited' }).getByRole('button', { name: 'Delete test' }).click();
  await expect(page.getByTestId('test-row')).toHaveCount(2);
  await page.getByRole('button', { name: 'Rubric & Formulas' }).click();
  await page.getByRole('button', { name: 'Create custom rubric' }).click();
  await page.getByLabel('Rubric title').fill('Browser rubric');
  await page.getByLabel('Criterion title').fill('Correctness');
  await page.getByRole('button', { name: 'Save rubric', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit rubric', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Import LMS ZIP' }).click();
  const archive = zipSync({ 'SV001/solution.py': strToU8('def add(a, b):\n    return a + b\n') });
  await page.locator('input[type=file]').setInputFiles({ name: 'browser-fixture.zip', mimeType: 'application/zip', buffer: Buffer.from(archive) });
  await page.getByRole('button', { name: 'Upload & Ingest' }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Grading Queue & Evidence Inspector' }).click();
  await expect(page.getByTestId('job-status')).toHaveText('completed', { timeout: 60_000 });
  await expect(page.getByText('2/2 tests passed', { exact: false })).toBeVisible();
  await page.getByLabel('Justification for Correctness').fill('Reviewed by instructor');
  await expect(page.getByLabel('Score for Correctness')).toHaveValue('10');
  await page.getByRole('button', { name: 'Confirm Grade', exact: true }).click();

  await page.getByRole('button', { name: 'Assignment & Tests', exact: true }).click();
  await expect(page.getByLabel('Instructions', { exact: true })).toHaveValue('Implement add(a, b)');
  await expect(page.getByLabel('Deadline (local time)', { exact: true })).toHaveValue('');
  await page.getByTestId('test-row').filter({ hasText: 'public_add' }).getByRole('button', { name: 'Edit test' }).click();
  await page.getByLabel('Python test code').fill('from solution import add\ndef test_add():\n    assert add(1, 2) == 99\n');
  await page.getByRole('button', { name: 'Save test', exact: true }).click();
  await expect(page.getByText('Test saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Grading Queue & Evidence Inspector' }).click();
  await page.getByRole('button', { name: 'Rerun grading', exact: true }).click();
  await expect(page.getByText('1/2 tests passed', { exact: false })).toBeVisible({ timeout: 60_000 });
  await expect(page.getByText('draft', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Confirm Grade', exact: true }).click();
  await expect(page.getByText('confirmed', { exact: true })).toHaveCount(2);
  await expect(page.getByText('ungraded', { exact: true })).toHaveCount(0);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Gradebook CSV' }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toMatch(/\.csv$/);
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv).toContain('SV001');
  expect(csv).toContain('confirmed');
  await page.getByLabel('Filter by grade status').selectOption('ungraded');
  await expect(page.getByText('No submissions match these filters.')).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await expect(page.getByLabel('Filter by grade status')).toHaveValue('all');
  const roster = page.getByRole('button').filter({ hasText: 'ID: SV001' });
  await roster.focus();
  await page.keyboard.press('Enter');
  await expect(roster).toHaveAttribute('aria-pressed', 'true');
  await page.route('**/submissions/*/grade', async route => {
    if (route.request().method() === 'PUT') await route.fulfill({ status: 409, json: { detail: 'Please wait for grading to finish.' } });
    else await route.continue();
  });
  await page.getByRole('button', { name: 'Confirm Grade', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Please wait for grading to finish.');
  await page.unroute('**/submissions/*/grade');
  await page.getByRole('button', { name: 'Confirm Grade', exact: true }).click();
  await expect(page.getByText('Grade confirmed.', { exact: true })).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/workstation-success.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Confirm Grade', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/workstation-mobile.png', fullPage: true });
  expect(serverErrors).toEqual([]);
});
